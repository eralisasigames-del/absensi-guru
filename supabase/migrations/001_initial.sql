on conflict (nama) do nothing;

alter table public.profiles enable row level security;
alter table public.attendance enable row level security;
alter table public.leave_types enable row level security;
alter table public.leave_requests enable row level security;

create or replace function public.is_kepala()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and role='kepala_sekolah' and status='aktif') $$;

create policy "profiles own read" on public.profiles for select to authenticated using (id=auth.uid() or public.is_kepala());
create policy "kepala manage profiles" on public.profiles for all to authenticated using (public.is_kepala()) with check (public.is_kepala());

create policy "attendance own read" on public.attendance for select to authenticated using (user_id=auth.uid() or public.is_kepala());
create policy "attendance own insert" on public.attendance for insert to authenticated with check (user_id=auth.uid());
create policy "attendance own update" on public.attendance for update to authenticated using (user_id=auth.uid() and not public.is_kepala()) with check (user_id=auth.uid());
create policy "kepala attendance all" on public.attendance for all to authenticated using (public.is_kepala()) with check (public.is_kepala());

create policy "leave types read" on public.leave_types for select to authenticated using (true);
create policy "leave own read" on public.leave_requests for select to authenticated using (user_id=auth.uid() or public.is_kepala());
create policy "leave own insert" on public.leave_requests for insert to authenticated with check (user_id=auth.uid() and status='pending');
create policy "kepala leave update" on public.leave_requests for update to authenticated using (public.is_kepala()) with check (public.is_kepala());
